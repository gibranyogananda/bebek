// FEATURE 2
// AUTOSCROLL
// ======================================================

document
    .querySelectorAll('a[href^="#"]')
    .forEach(link => {

        link.addEventListener(
            "click",
            function (event) {

                const targetId =
                    this.getAttribute("href");


                if (
                    !targetId ||
                    targetId === "#"
                ) {

                    return;

                }


                const target =
                    document.querySelector(
                        targetId
                    );


                if (!target) {

                    return;

                }


                event.preventDefault();


                const navbar =
                    document.querySelector(
                        ".navbar"
                    );


                const navbarHeight =
                    navbar
                        ? navbar.offsetHeight
                        : 0;


                const targetPosition =
                    target
                        .getBoundingClientRect()
                        .top +
                    window.pageYOffset -
                    navbarHeight;


                window.scrollTo({

                    top: targetPosition,

                    behavior: "smooth"

                });


                // Tutup navbar mobile

                const navbarCollapse =
                    document.querySelector(
                        ".navbar-collapse"
                    );


                if (
                    navbarCollapse &&
                    navbarCollapse.classList.contains(
                        "show"
                    ) &&
                    typeof bootstrap !==
                        "undefined"
                ) {

                    bootstrap.Collapse
                        .getOrCreateInstance(
                            navbarCollapse
                        )
                        .hide();

                }

            }
        );

    });


