/* =========================================
   ELEMENT MENU
========================================= */

const menuTabs = document.querySelectorAll(".menu-tab");
const menuItemsContainer = document.getElementById("menuItems");
const menuImage = document.getElementById("menuImage");
const menuCategoryTitle = document.getElementById("menuCategoryTitle");


/* =========================================
   TAMPILKAN MENU
========================================= */

function showMenu(category) {

    const data = menuData[category];

    if (!data) {
        return;
    }


    // Judul kategori
    menuCategoryTitle.textContent = data.title;


    // Foto menu
    menuImage.src = data.image;
    menuImage.alt = data.title;


    // Kosongkan daftar lama
    menuItemsContainer.innerHTML = "";


    // Buat daftar menu
    data.items.forEach(function(item) {

        const menuItem = document.createElement("div");

        menuItem.className = "menu-item";

        menuItem.innerHTML = `
            <span class="menu-item-name">
                ${item[0]}
            </span>

            <span class="menu-item-price">
                ${item[1]}
            </span>
        `;

        menuItemsContainer.appendChild(menuItem);

    });

}


/* =========================================
   KLIK KATEGORI MENU
========================================= */

menuTabs.forEach(function(tab) {

    tab.addEventListener("click", function() {

        // Hilangkan active dari semua
        menuTabs.forEach(function(item) {
            item.classList.remove("active");
        });


        // Aktifkan tombol yang dipilih
        this.classList.add("active");


        // Ambil kategori
        const category = this.dataset.category;


        // Tampilkan menu
        showMenu(category);

    });

});


/* =========================================
   ACTIVE NAVBAR SAAT SCROLL
========================================= */

const sections = document.querySelectorAll("section[id]");
const navLinks = document.querySelectorAll(".nav-link");


window.addEventListener("scroll", function() {

    let currentSection = "";

    sections.forEach(function(section) {

        const sectionTop = section.offsetTop - 120;
        const sectionHeight = section.offsetHeight;

        if (
            window.scrollY >= sectionTop &&
            window.scrollY < sectionTop + sectionHeight
        ) {
            currentSection = section.getAttribute("id");
        }

    });


    navLinks.forEach(function(link) {

        link.classList.remove("active");

        if (
            link.getAttribute("href") === "#" + currentSection
        ) {
            link.classList.add("active");
        }

    });

});


/* =========================================
   SMOOTH SCROLL NAVBAR
========================================= */

navLinks.forEach(function(link) {

    link.addEventListener("click", function(event) {

        const targetId = this.getAttribute("href");

        if (
            targetId &&
            targetId.startsWith("#")
        ) {

            const target = document.querySelector(targetId);

            if (target) {

                event.preventDefault();

                target.scrollIntoView({
                    behavior: "smooth",
                    block: "start"
                });

            }

        }

    });

});


/* =========================================
   CLOSE NAVBAR MOBILE
========================================= */

navLinks.forEach(function(link) {

    link.addEventListener("click", function() {

        const navbar = document.querySelector(".navbar-collapse");

        if (
            navbar &&
            navbar.classList.contains("show")
        ) {

            const toggle = document.querySelector(".navbar-toggler");

            toggle.click();

        }

    });

});


